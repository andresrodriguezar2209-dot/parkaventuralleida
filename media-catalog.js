export function mergePhotos(...lists) {
  const seen = new Set();
  return lists.flat().filter(photo => {
    const key = decodeURIComponent(photo.url || photo.storage_path || photo.id);
    if (seen.has(key)) return false;
    seen.add(key); return true;
  });
}
